#!/usr/bin/env python3
"""Export NES Tetris disassembly assets into a C header for the PSP port.

Reads:
  - gfx/*.png           (decoded NES CHR pattern tables, 128px wide, 4 colors)
  - gfx/nametables/*.bin
  - palettes + tileset order from tetris.asm (CHR bank layout)

Writes psp/source/data/assets.h with:
  - tiles_game / tiles_menu : uint8_t[256][64] palette-index pixel arrays (row-major 8x8)
  - nt_* nametables (960 bytes each)
"""
import os, sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), "..")
OUT = os.path.normpath(os.path.join(ROOT, "psp", "source", "data", "assets.h"))

def decode_chr(png_path):
    """Return list of 256 tiles, each 64 bytes (palette indices 0..3), row-major."""
    im = Image.open(png_path).convert("L")
    w, h = im.size
    assert w == 128, f"{png_path}: expected width 128, got {w}"
    px = im.load()
    # Map unique gray values to indices 0..3 sorted ascending
    colors = sorted(set(px[x, y] for y in range(h) for x in range(w)))
    lut = {c: i for i, c in enumerate(colors)}
    tiles_per_row = 16
    tiles = []
    for t in range((w // 8) * (h // 8)):
        tx = (t % tiles_per_row) * 8
        ty = (t // tiles_per_row) * 8
        data = bytearray(64)
        for r in range(8):
            for c in range(8):
                data[r * 8 + c] = lut[px[tx + c, ty + r]]
        tiles.append(bytes(data))
    return tiles

def emit_array(f, name, data, per_line=16):
    f.write(f"static const unsigned char {name}[{len(data)}] = {{\n")
    for i in range(0, len(data), per_line):
        f.write("    " + ",".join(str(b) for b in data[i:i+per_line]) + ",\n")
    f.write("};\n\n")

def main():
    game = decode_chr(os.path.join(ROOT, "gfx/game_tileset.png"))
    menu = decode_chr(os.path.join(ROOT, "gfx/title_menu_tileset.png"))
    assert len(game) == 256 and len(menu) == 256

    nts = {
        "nt_legal":      "gfx/nametables/legal_screen_nametable.bin",
        "nt_title":      "gfx/nametables/title_screen_nametable.bin",
        "nt_type_menu":  "gfx/nametables/game_type_menu_nametable.bin",
        "nt_level_menu": "gfx/nametables/level_menu_nametable.bin",
        "nt_game":       "gfx/nametables/game_nametable.bin",
        "nt_highscores": "gfx/nametables/high_scores_nametable.bin",
        "nt_enter_hs":   "gfx/nametables/enter_high_score_nametable.bin",
    }

    with open(OUT, "w") as f:
        f.write("/* Auto-generated by tools/export_nes_assets.py -- do not edit. */\n")
        f.write("#ifndef ASSETS_H\n#define ASSETS_H\n\n")
        f.write("/* NES pattern tables decoded to 8x8 tiles of palette indices (0..3).\n"
                "   Index = PPU tile ID; row-major pixels within each tile. */\n")
        for name, tiles in (("tiles_game", game), ("tiles_menu", menu)):
            flat = b"".join(tiles)
            emit_array(f, name, flat)
        for name, path in nts.items():
            p = os.path.join(ROOT, path)
            if os.path.exists(p):
                with open(p, "rb") as g:
                    emit_array(f, name, g.read())
        f.write("#endif /* ASSETS_H */\n")
    print("wrote", OUT)

if __name__ == "__main__":
    main()
